/// <summary>S3 兼容对象存储适配器。对象键只由租户和版本 ID 组成。</summary>
public sealed class S3ObjectStorage : IObjectStorage, IDisposable
{
    private readonly IAmazonS3 client;
    private readonly string bucket;

    /// <summary>从 Knowledge:Storage 配置创建客户端。</summary>
    public S3ObjectStorage(IConfiguration configuration)
    {
        var section = configuration.GetSection("Knowledge:Storage");
        var endpoint = section["Endpoint"]?.Trim();
        bucket = Require(section["Bucket"], "Knowledge:Storage:Bucket");
        var accessKey = Require(section["AccessKey"], "Knowledge:Storage:AccessKey");
        var secretKey = Require(section["SecretKey"], "Knowledge:Storage:SecretKey");
        var region = section["Region"]?.Trim() ?? "us-east-1";
        var forcePathStyle = bool.TryParse(section["ForcePathStyle"], out var parsed) && parsed;
        var clientConfig = new AmazonS3Config
        {
            AuthenticationRegion = region,
            ForcePathStyle = forcePathStyle,
            ServiceURL = string.IsNullOrWhiteSpace(endpoint) ? null : endpoint,
            UseHttp = endpoint?.StartsWith("http://", StringComparison.OrdinalIgnoreCase) == true
        };
        client = new AmazonS3Client(accessKey, secretKey, clientConfig);
    }

    /// <summary>供测试注入 S3 客户端的构造函数。</summary>
    public S3ObjectStorage(IAmazonS3 client, string bucket)
    {
        this.client = client;
        this.bucket = Require(bucket, nameof(bucket));
    }

    /// <inheritdoc />
    public async Task<string> PutAsync(Guid tenantId, Guid versionId, Stream content,
        CancellationToken cancellationToken = default)
    {
        var key = Key(tenantId, versionId);
        try
        {
            await client.PutObjectAsync(new PutObjectRequest
            {
                BucketName = bucket,
                Key = key,
                InputStream = content,
                AutoCloseStream = false,
                AutoResetStreamPosition = false
            }, cancellationToken);
            return key;
        }
        catch
        {
            // S3 PUT is atomic, but a compatible gateway may acknowledge late.
            // Best-effort cleanup prevents an orphan from counting against quota.
            try { await client.DeleteObjectAsync(bucket, key, CancellationToken.None); } catch { /* compensation only */ }
            throw;
        }
    }

    /// <inheritdoc />
    public async Task PutAtAsync(string objectKey, Stream content, CancellationToken cancellationToken = default)
    {
        if (!ContentImageKeys.IsValid(objectKey))
            throw new ArgumentException("Object key was not generated by the content image service.", nameof(objectKey));
        try
        {
            await client.PutObjectAsync(new PutObjectRequest
            {
                BucketName = bucket,
                Key = objectKey,
                InputStream = content,
                AutoCloseStream = false,
                AutoResetStreamPosition = false
            }, cancellationToken);
        }
        catch
        {
            try { await client.DeleteObjectAsync(bucket, objectKey, CancellationToken.None); } catch { /* compensation only */ }
            throw;
        }
    }

    /// <inheritdoc />
    public async Task<Stream?> OpenReadAsync(string objectKey, CancellationToken cancellationToken = default)
    {
        ValidateServerKey(objectKey);
        try
        {
            var response = await client.GetObjectAsync(new GetObjectRequest { BucketName = bucket, Key = objectKey }, cancellationToken);
            return new S3ResponseStream(response);
        }
        catch (AmazonS3Exception exception) when (exception.StatusCode == HttpStatusCode.NotFound)
        {
            return null;
        }
    }

    /// <inheritdoc />
    public async Task DeleteAsync(string objectKey, CancellationToken cancellationToken = default)
    {
        ValidateServerKey(objectKey);
        await client.DeleteObjectAsync(bucket, objectKey, cancellationToken);
    }

    /// <inheritdoc />
    public void Dispose() => client.Dispose();

    private static string Key(Guid tenantId, Guid versionId) => $"{tenantId:N}/{versionId:N}/source";
    private static void ValidateServerKey(string value)
    {
        if (ContentImageKeys.IsValid(value)) return;
        if (string.IsNullOrWhiteSpace(value) || value.StartsWith('/') || value.Contains("..", StringComparison.Ordinal)
            || value.Contains('\\') || value.Split('/').Length != 3 || value.EndsWith("/source", StringComparison.Ordinal) == false)
            throw new ArgumentException("Object key was not generated by the knowledge service.", nameof(value));
        if (!Guid.TryParseExact(value.Split('/')[0], "N", out _) || !Guid.TryParseExact(value.Split('/')[1], "N", out _))
            throw new ArgumentException("Object key was not generated by the knowledge service.", nameof(value));
    }

    private static string Require(string? value, string name) => string.IsNullOrWhiteSpace(value)
        ? throw new InvalidOperationException($"Knowledge storage setting '{name}' is required.") : value.Trim();

    private sealed class S3ResponseStream(GetObjectResponse response) : Stream
    {
        private readonly Stream inner = response.ResponseStream;
        protected override void Dispose(bool disposing)
        {
            if (disposing) response.Dispose();
            base.Dispose(disposing);
        }
        public override bool CanRead => inner.CanRead;
        public override bool CanSeek => inner.CanSeek;
        public override bool CanWrite => false;
        public override long Length => inner.Length;
        public override long Position { get => inner.Position; set => inner.Position = value; }
        public override void Flush() => inner.Flush();
        public override Task FlushAsync(CancellationToken cancellationToken) => inner.FlushAsync(cancellationToken);
        public override int Read(byte[] buffer, int offset, int count) => inner.Read(buffer, offset, count);
        public override int Read(Span<byte> buffer) => inner.Read(buffer);
        public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken) => inner.ReadAsync(buffer, offset, count, cancellationToken);
        public override ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default) => inner.ReadAsync(buffer, cancellationToken);
        public override long Seek(long offset, SeekOrigin origin) => inner.Seek(offset, origin);
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
        public override void Write(ReadOnlySpan<byte> buffer) => throw new NotSupportedException();
        public override Task WriteAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken) => throw new NotSupportedException();
        public override ValueTask WriteAsync(ReadOnlyMemory<byte> buffer, CancellationToken cancellationToken = default) => throw new NotSupportedException();
    }
}

/// <summary>OpenAI-compatible Embeddings HTTP 适配器。</summary>
public sealed class OpenAiCompatibleEmbeddingProvider : IEmbeddingProvider
{
    private readonly HttpClient httpClient;
    private readonly string url;
    private readonly string model;
    private readonly string? apiKey;
    private readonly int batchSize;
    private readonly TimeSpan timeout;

    /// <summary>从 Knowledge:Embedding 配置创建适配器。</summary>
    public OpenAiCompatibleEmbeddingProvider(HttpClient httpClient, IConfiguration configuration)
    {
        this.httpClient = httpClient;
        var section = configuration.GetSection("Knowledge:Embedding");
        url = Require(section["Url"], "Knowledge:Embedding:Url");
        model = Require(section["Model"], "Knowledge:Embedding:Model");
        apiKey = string.IsNullOrWhiteSpace(section["ApiKey"]) ? null : section["ApiKey"]!.Trim();
        var dimensions = ParsePositive(section["Dimensions"], 0, 8192, "Knowledge:Embedding:Dimensions");
        Dimensions = dimensions;
        batchSize = ParsePositive(section["BatchSize"], 32, 256, "Knowledge:Embedding:BatchSize");
        var timeoutSeconds = ParsePositive(section["TimeoutSeconds"], 60, 600, "Knowledge:Embedding:TimeoutSeconds");
        timeout = TimeSpan.FromSeconds(timeoutSeconds);
        Model = model;
        Profile = ProfileHash(url, model, dimensions);
    }

    /// <summary>供单元测试注入 URL、模型和超时的构造函数。</summary>
    public OpenAiCompatibleEmbeddingProvider(HttpClient httpClient, string url, string model, int dimensions,
        string? apiKey = null, int batchSize = 32, TimeSpan? timeout = null)
    {
        this.httpClient = httpClient;
        this.url = Require(url, nameof(url));
        this.model = Require(model, nameof(model));
        if (dimensions < 0 || dimensions > 8192) throw new ArgumentOutOfRangeException(nameof(dimensions));
        if (batchSize is < 1 or > 256) throw new ArgumentOutOfRangeException(nameof(batchSize));
        Dimensions = dimensions; Model = model; Profile = ProfileHash(url, model, dimensions);
        this.apiKey = apiKey; this.batchSize = batchSize; this.timeout = timeout ?? TimeSpan.FromSeconds(60);
    }

    /// <inheritdoc />
    public string Profile { get; }
    /// <summary>当前模型标识。</summary>
    public string Model { get; }
    /// <summary>期望维度；0 表示由服务端返回并在本批次内保持一致。</summary>
    public int Dimensions { get; }

    /// <inheritdoc />
    public async Task<IReadOnlyList<float[]>> EmbedAsync(IReadOnlyList<string> texts,
        CancellationToken cancellationToken = default)
    {
        if (texts is null) throw new ArgumentNullException(nameof(texts));
        if (texts.Any(string.IsNullOrWhiteSpace)) throw new ArgumentException("Embedding input cannot be empty.", nameof(texts));
        var output = new float[texts.Count][];
        for (var offset = 0; offset < texts.Count; offset += batchSize)
        {
            var count = Math.Min(batchSize, texts.Count - offset);
            var batch = texts.Skip(offset).Take(count).ToArray();
            using var request = new HttpRequestMessage(HttpMethod.Post, url);
            request.Content = JsonContent.Create(new EmbeddingRequest(model, batch, Dimensions > 0 ? Dimensions : null));
            if (!string.IsNullOrWhiteSpace(apiKey)) request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", apiKey);
            using var timeoutSource = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
            timeoutSource.CancelAfter(timeout);
            using var response = await httpClient.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, timeoutSource.Token);
            if (!response.IsSuccessStatusCode)
                throw new InvalidOperationException($"Embedding provider returned HTTP {(int)response.StatusCode}.");
            await using var stream = await response.Content.ReadAsStreamAsync(timeoutSource.Token);
            using var document = await JsonDocument.ParseAsync(stream, cancellationToken: timeoutSource.Token);
            var vectors = ParseVectors(document.RootElement, count, Dimensions);
            for (var i = 0; i < vectors.Length; i++) output[offset + i] = vectors[i];
        }
        return output;
    }

    private static float[][] ParseVectors(JsonElement root, int expectedCount, int expectedDimensions)
    {
        if (!root.TryGetProperty("data", out var data) || data.ValueKind != JsonValueKind.Array || data.GetArrayLength() != expectedCount)
            throw new InvalidOperationException("Embedding response data count is invalid.");
        var result = new float[expectedCount][]; var seen = new bool[expectedCount];
        foreach (var item in data.EnumerateArray())
        {
            if (!item.TryGetProperty("index", out var indexValue) || !indexValue.TryGetInt32(out var index) || index < 0 || index >= expectedCount || seen[index])
                throw new InvalidOperationException("Embedding response index is invalid.");
            if (!item.TryGetProperty("embedding", out var embedding) || embedding.ValueKind != JsonValueKind.Array)
                throw new InvalidOperationException("Embedding response vector is missing.");
            var vector = embedding.EnumerateArray().Select(value => value.GetSingle()).ToArray();
            var dimensions = expectedDimensions > 0 ? expectedDimensions : vector.Length;
            if (vector.Length != dimensions || vector.Any(value => float.IsNaN(value) || float.IsInfinity(value)))
                throw new InvalidOperationException("Embedding response dimensions or numeric values are invalid.");
            result[index] = vector; seen[index] = true;
        }
        if (seen.Any(item => !item)) throw new InvalidOperationException("Embedding response indexes are incomplete.");
        return result;
    }

    private sealed record EmbeddingRequest(string model, IReadOnlyList<string> input, int? dimensions);
    private static string ProfileHash(string url, string model, int dimensions) => "openai-" + Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes($"{url.TrimEnd('/')}|{model}|{dimensions}")))[..16].ToLowerInvariant();
    private static string Require(string? value, string name) => string.IsNullOrWhiteSpace(value) ? throw new InvalidOperationException($"Embedding setting '{name}' is required.") : value.Trim();
    private static int ParsePositive(string? value, int fallback, int maximum, string name) => string.IsNullOrWhiteSpace(value) ? fallback : int.TryParse(value, out var parsed) && parsed > 0 && parsed <= maximum ? parsed : throw new InvalidOperationException($"Embedding setting '{name}' is invalid.");
}

/// <summary>Qdrant REST 向量索引适配器。</summary>
public sealed class QdrantVectorIndex : IVectorIndex
{
    private readonly HttpClient httpClient;
    private readonly string endpoint;
    private readonly string collectionPrefix;
    private readonly string? apiKey;
    private readonly string profile;
    private readonly int dimensions;
    private readonly SemaphoreSlim ensureLock = new(1, 1);

    /// <summary>从 Knowledge:Qdrant 配置连接，并以当前 Embedding 档案隔离集合。</summary>
    public QdrantVectorIndex(HttpClient httpClient, IConfiguration configuration, IEmbeddingProvider embeddingProvider)
    {
        this.httpClient = httpClient;
        var section = configuration.GetSection("Knowledge:Qdrant");
        endpoint = (section["Url"] ?? configuration["Knowledge:Vector:Url"] ?? "http://localhost:6333").TrimEnd('/');
        collectionPrefix = Sanitize(section["CollectionPrefix"] ?? "jogeoai_knowledge");
        apiKey = section["ApiKey"] ?? configuration["Knowledge:Vector:ApiKey"];
        profile = embeddingProvider.Profile;
        dimensions = embeddingProvider.Dimensions;
        if (dimensions <= 0)
            throw new InvalidOperationException("Qdrant requires a configured positive embedding dimension.");
    }

    /// <summary>供 HTTP 单元测试注入服务地址的构造函数。</summary>
    public QdrantVectorIndex(HttpClient httpClient, string endpoint, string profile, int dimensions, string collectionPrefix = "jogeoai_knowledge", string? apiKey = null)
    {
        this.httpClient = httpClient; this.endpoint = endpoint.TrimEnd('/'); this.profile = profile; this.dimensions = dimensions; this.collectionPrefix = Sanitize(collectionPrefix); this.apiKey = apiKey;
    }

    /// <inheritdoc />
    public async Task UpsertAsync(Guid tenantId, Guid versionId, IReadOnlyList<KnowledgeChunk> chunks,
        IReadOnlyList<float[]> vectors, CancellationToken cancellationToken = default)
    {
        ValidateVectors(vectors, chunks.Count);
        if (chunks.Count == 0) return;
        var collection = await EnsureCollectionAsync(cancellationToken);
        var points = chunks.Zip(vectors, (chunk, vector) => new { id = chunk.ChunkId, vector, payload = new { tenantId = tenantId.ToString(), versionId = versionId.ToString(), chunkId = chunk.ChunkId.ToString() } }).ToArray();
        await SendJsonAsync(HttpMethod.Put, $"{endpoint}/collections/{Uri.EscapeDataString(collection)}/points?wait=true", new { points }, cancellationToken);
    }

    /// <inheritdoc />
    public async Task<IReadOnlyList<(Guid ChunkId, double Score)>> SearchAsync(Guid tenantId, IReadOnlySet<Guid> versionIds,
        float[] query, int topK, CancellationToken cancellationToken = default)
    {
        ValidateVector(query);
        if (versionIds.Count == 0 || topK <= 0) return [];
        var collection = await EnsureCollectionAsync(cancellationToken);
        var body = new { vector = query, limit = Math.Clamp(topK, 1, 100), with_payload = true, filter = new { must = new object[] { new { key = "tenantId", match = new { value = tenantId.ToString() } }, new { key = "versionId", match = new { any = versionIds.Select(item => item.ToString()).ToArray() } } } } };
        using var document = await SendJsonAsync(HttpMethod.Post, $"{endpoint}/collections/{Uri.EscapeDataString(collection)}/points/search", body, cancellationToken);
        if (!document.RootElement.TryGetProperty("result", out var result) || result.ValueKind != JsonValueKind.Array) throw new InvalidOperationException("Qdrant response did not contain results.");
        var output = new List<(Guid, double)>();
        foreach (var item in result.EnumerateArray())
        {
            var idText = item.TryGetProperty("payload", out var payload) && payload.TryGetProperty("chunkId", out var chunkId) ? chunkId.GetString() : item.GetProperty("id").GetString();
            if (Guid.TryParse(idText, out var id) && item.TryGetProperty("score", out var score) && score.TryGetDouble(out var numeric) && !double.IsNaN(numeric) && !double.IsInfinity(numeric)) output.Add((id, numeric));
        }
        return output;
    }

    /// <inheritdoc />
    public async Task DeleteVersionAsync(Guid tenantId, Guid versionId, CancellationToken cancellationToken = default)
    {
        var collection = await EnsureCollectionAsync(cancellationToken);
        var filter = new { filter = new { must = new object[] { new { key = "tenantId", match = new { value = tenantId.ToString() } }, new { key = "versionId", match = new { value = versionId.ToString() } } } } };
        await SendJsonAsync(HttpMethod.Post, $"{endpoint}/collections/{Uri.EscapeDataString(collection)}/points/delete?wait=true", filter, cancellationToken);
    }

    private async Task<string> EnsureCollectionAsync(CancellationToken cancellationToken)
    {
        var collection = $"{collectionPrefix}_{Sanitize(profile)}";
        await ensureLock.WaitAsync(cancellationToken);
        try
        {
            using var response = await SendAsync(HttpMethod.Get, $"{endpoint}/collections/{Uri.EscapeDataString(collection)}", null, cancellationToken, allowNotFound: true);
            if (response.StatusCode == HttpStatusCode.NotFound)
            {
                response.Dispose();
                try { using var created = await SendAsync(HttpMethod.Put, $"{endpoint}/collections/{Uri.EscapeDataString(collection)}", new { vectors = new { size = dimensions, distance = "Cosine" } }, cancellationToken); }
                catch (InvalidOperationException) { /* another worker may have created it; verify below */ }
            }
            else if (!response.IsSuccessStatusCode) throw new InvalidOperationException($"Qdrant collection check returned HTTP {(int)response.StatusCode}.");
            using var verified = await SendAsync(HttpMethod.Get, $"{endpoint}/collections/{Uri.EscapeDataString(collection)}", null, cancellationToken);
            using var json = await JsonDocument.ParseAsync(await verified.Content.ReadAsStreamAsync(cancellationToken), cancellationToken: cancellationToken);
            var size = FindVectorSize(json.RootElement);
            if (size != dimensions) throw new InvalidOperationException($"Qdrant collection dimension {size} does not match configured {dimensions}.");
            return collection;
        }
        finally { ensureLock.Release(); }
    }

    private async Task<JsonDocument> SendJsonAsync(HttpMethod method, string url, object body, CancellationToken cancellationToken)
    {
        using var response = await SendAsync(method, url, body, cancellationToken);
        return await JsonDocument.ParseAsync(await response.Content.ReadAsStreamAsync(cancellationToken), cancellationToken: cancellationToken);
    }

    private async Task<HttpResponseMessage> SendAsync(HttpMethod method, string url, object? body, CancellationToken cancellationToken, bool allowNotFound = false)
    {
        using var request = new HttpRequestMessage(method, url);
        if (body is not null) request.Content = JsonContent.Create(body);
        if (!string.IsNullOrWhiteSpace(apiKey)) request.Headers.Add("api-key", apiKey);
        var response = await httpClient.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, cancellationToken);
        if (!response.IsSuccessStatusCode && !(allowNotFound && response.StatusCode == HttpStatusCode.NotFound)) { response.Dispose(); throw new InvalidOperationException($"Qdrant returned HTTP {(int)response.StatusCode}."); }
        return response;
    }

    private void ValidateVectors(IReadOnlyList<float[]> vectors, int expectedCount) { if (vectors.Count != expectedCount) throw new ArgumentException("Vector count does not match chunk count."); foreach (var vector in vectors) ValidateVector(vector); }
    private void ValidateVector(float[] vector) { if (vector.Length != dimensions || vector.Any(item => float.IsNaN(item) || float.IsInfinity(item))) throw new ArgumentException("Vector dimensions or numeric values are invalid."); }
    private static int FindVectorSize(JsonElement root)
    {
        var current = root.GetProperty("result").GetProperty("config").GetProperty("params").GetProperty("vectors");
        if (current.ValueKind == JsonValueKind.Object && current.TryGetProperty("size", out var direct)) return direct.GetInt32();
        foreach (var property in current.EnumerateObject()) if (property.Value.TryGetProperty("size", out var named)) return named.GetInt32();
        throw new InvalidOperationException("Qdrant collection vector size is missing.");
    }
    private static string Sanitize(string value)
    {
        var cleaned = new string(value.Where(item => char.IsLetterOrDigit(item) || item is '_' or '-').ToArray());
        if (cleaned.Length == 0) cleaned = "knowledge";
        return cleaned[..Math.Min(64, cleaned.Length)];
    }
}
