-- 034_citation_domain_types.sql
-- 引用来源域名类型字典：品牌官网 / 媒体平台 / 电商B2B / 其他，全局共享、不区分租户。
-- 首期只用于内容详情「推荐渠道」（GET .../article-monitoring/recommended-channels 仅返回 media_platform），
-- 不改变已冻结的分析口径 website-category-v1。
-- 种子来自 2026-10-28 本机库 1494 个引用域名的 AI 分类 + 用户审核定稿（docx/citation-domain-types-review.xlsx，
-- Trellis 10-28-content-recommended-channels），共 1265 条规则。
-- 匹配：精确域名优先，其次是 include_subdomains=1 且主机以「.domain」结尾的最长规则；未命中视为未分类（不推荐）。
-- 手动执行于 001–033 之后（mysql 客户端须 --default-character-set=utf8mb4）；API / Worker 启动不会执行本迁移。
-- 可重放：建表 IF NOT EXISTS；种子 ON DUPLICATE KEY UPDATE 会把同名规则恢复为本文件的值（不删除库中额外规则）。
-- 未执行本文件的库上，推荐渠道接口因缺表返回 500，其他接口不受影响：发布顺序为「先迁移再发 API」。
-- 回滚：API 回退后本表保留无害；确认不再需要时再 DROP TABLE citation_domain_types。

CREATE TABLE IF NOT EXISTS citation_domain_types (
    -- 规范化 ASCII 主机（canonical-host-ownership-v1：小写、去一个前导 www.），与域名榜 domain 同口径。
    domain VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    -- 1：该域名及其全部子域；0：仅该域名。
    include_subdomains TINYINT(1) NOT NULL,
    site_type VARCHAR(24) NOT NULL,
    -- 同一平台多条规则共用（如 douyin：douyin.com、iesdouyin.com），推荐时按它合并；为空时按规则域名合并。
    platform_key VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    -- 中文显示名与发布入口，只用于媒体平台。
    platform_name VARCHAR(64) NULL,
    publish_url VARCHAR(512) NULL,
    -- ai_reviewed：AI 分类经用户审核；manual：人工补充。
    source VARCHAR(16) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (domain),
    CONSTRAINT ck_citation_domain_types_type CHECK (site_type IN ('brand_site', 'media_platform', 'ecommerce_b2b', 'other')),
    CONSTRAINT ck_citation_domain_types_subdomains CHECK (include_subdomains IN (0, 1)),
    CONSTRAINT ck_citation_domain_types_source CHECK (source IN ('ai_reviewed', 'manual')),
    CONSTRAINT ck_citation_domain_types_url CHECK (publish_url IS NULL OR publish_url LIKE 'https://%'),
    CONSTRAINT ck_citation_domain_types_media CHECK (site_type = 'media_platform'
        OR (platform_key IS NULL AND platform_name IS NULL AND publish_url IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

